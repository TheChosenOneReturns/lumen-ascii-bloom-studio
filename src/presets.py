class PresetManager:
    def __init__(self, presets_dir: Path) -> None:
        self.presets_dir = presets_dir
        self.presets_dir.mkdir(parents=True, exist_ok=True)
        self.presets: Dict[str, ShaderParams] = {}
        self.categories: Dict[str, str] = {}
        self.reload()

    def reload(self) -> None:
        self.presets = get_builtin_presets()
        self.categories = dict(PRESET_CATEGORIES)
        for path in sorted(self.presets_dir.glob("*.json")):
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
                name = data.get("name", path.stem)
                params = ShaderParams.from_dict(data.get("params", data))
                self.presets[name] = params
                self.categories[name] = data.get("category", "CUSTOM")
            except Exception:
                continue

    def names_for_category(self, category: str) -> List[str]:
        if category == "TODOS":
            return list(self.presets.keys())
        return [name for name in self.presets.keys() if self.categories.get(name, "CUSTOM") == category]

    def save_preset(self, name: str, params: ShaderParams) -> Path:
        safe = "".join(ch if (ch.isalnum() or ch in " _-") else "_" for ch in name).strip()
        if not safe:
            safe = "Custom_Preset"
        out_path = self.presets_dir / f"{safe}.json"
        payload = {"name": name.strip() or safe, "category": "CUSTOM", "params": params.to_dict()}
        out_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
        self.presets[payload["name"]] = params.clone()
        self.categories[payload["name"]] = "CUSTOM"
        return out_path
